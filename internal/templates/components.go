// Funcs returns the template helpers. assetFS is the embedded file system
// containing static/, used to fingerprint asset URLs for long-lived caching.
func Funcs(assetFS fs.FS) template.FuncMap {
	versions := map[string]string{}
	return template.FuncMap{
		"icon": Icon,
		// asset returns /static/<name>?v=<hash> so assets can be cached
		// immutably and still bust on deploy.
		"asset": func(name string) string {
			if v, ok := versions[name]; ok {
				return v
			}
			url := "/static/" + name
			if b, err := fs.ReadFile(assetFS, path.Join("static", name)); err == nil {
				sum := sha256.Sum256(b)
				url += "?v=" + hex.EncodeToString(sum[:6])
			}
			versions[name] = url
			return url
		},
		"dict": func(kv ...any) (map[string]any, error) {
			if len(kv)%2 != 0 {
				return nil, fmt.Errorf("dict: odd number of arguments")
			}
			m := make(map[string]any, len(kv)/2)
			for i := 0; i < len(kv); i += 2 {
				key, ok := kv[i].(string)
				if !ok {
					return nil, fmt.Errorf("dict: key %v is not a string", kv[i])
				}
				m[key] = kv[i+1]
			}
			return m, nil
		},
		"add":  func(a, b int) int { return a + b },
		"href": Href,
		"tel":  Tel,
		// Shared with server-side validation in internal/phone.
		"phonePattern": func() string { return phone.InputPattern },
		"phoneHint":    func() string { return phone.InputHint },
	}
}

// Href marks a content-configured link as safe. html/template rewrites
// schemes other than http(s)/mailto to "#ZgotmplZ"; Href additionally allows
// tel: and in-page/relative links and replaces anything else with "#".
func Href(s string) template.URL {
	s = strings.TrimSpace(s)
	lower := strings.ToLower(s)
	if strings.HasPrefix(lower, "//") {
		return "#"
	}
	for _, prefix := range []string{"https://", "http://", "mailto:", "tel:", "/", "#"} {
		if strings.HasPrefix(lower, prefix) {
			return template.URL(s) //nolint:gosec // scheme allow-listed above
		}
	}
	return "#"
}

// Tel builds a tel: URL from a human-formatted phone number.
func Tel(phone string) template.URL {
	var b strings.Builder
	b.WriteString("tel:")
	for i, r := range phone {
		if (r >= '0' && r <= '9') || (r == '+' && i == 0) {
			b.WriteRune(r)
		}
	}
	return template.URL(b.String()) //nolint:gosec // digits and leading + only
}

// Icon renders an inline SVG icon (Lucide-style, 24×24, stroke-based).
// Unknown names return an error so typos fail tests instead of rendering
// silently blank.
func Icon(name, class string) (template.HTML, error) {
	body, ok := icons[name]
	if !ok {
		return "", fmt.Errorf("icon: unknown icon %q", name)
	}
	var b strings.Builder
	b.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false"`)
	if class != "" {
		b.WriteString(` class="` + html.EscapeString(class) + `"`)
	}
	b.WriteString(">" + body + "</svg>")
	return template.HTML(b.String()), nil //nolint:gosec // static, trusted SVG markup
}

// HasIcon reports whether name is a known icon.
func HasIcon(name string) bool {
	_, ok := icons[name]
	return ok
}

